#ifndef SECP256K1_MODULE_FROST_BENCH_H
#define SECP256K1_MODULE_FROST_BENCH_H

#include "../../../include/secp256k1_frost.h"
#include "fill_random.h"

#define BENCH_FROST_MSGLEN (32)
#define BENCH_FROST_MAX_PARTICIPANTS 3
#define BENCH_FROST_THR_PARTICIPANTS 2

typedef struct {
  secp256k1_frost_keypair *keypairs;

  /*
   * State used only by the signing benchmark.
   *
   * sign_nonce is freshly generated by bench_frost_sign_setup() before
   * each benchmark run. secp256k1_frost_sign() consumes its secret nonce
   * material, and bench_frost_sign_teardown() destroys the zeroed object
   * after the run.
   */
  secp256k1_frost_nonce *sign_nonce;
  secp256k1_frost_nonce_commitment *signing_commitments;

  /*
   * Immutable state used by the aggregation and verification benchmarks.
   * It is prepared once during initialization and is independent from the
   * one-shot nonce objects used by the signing benchmark.
   */
  secp256k1_frost_nonce_commitment *aggregate_commitments;
  secp256k1_frost_pubkey *public_keys;
  secp256k1_frost_signature_share *signature_shares;
  unsigned char signature[FROST_SIGNATURE_SIZE];
} secp256k1_frost_data_per_iter;

typedef struct {
    secp256k1_context *ctx;
    int n;
    const unsigned char **msgs;
    secp256k1_frost_data_per_iter *state;
} bench_frost_data;

static void bench_frost_sign_setup(void* arg) {
    bench_frost_data *data = (bench_frost_data *)arg;
    secp256k1_frost_nonce *nonce;
    unsigned char hiding_seed[32];
    unsigned char binding_seed[32];
    int i, j, signer_index;

    /*
     * Prepare a fresh signing session for every timed iteration.
     *
     * Nonce generation and commitment construction occur outside the timed
     * region, so bench_frost_sign() measures only signature-share generation.
     */
    for (i = 0; i < data->n; i++) {
        signer_index = i % BENCH_FROST_THR_PARTICIPANTS;

        if (data->state[i].sign_nonce != NULL) {
            secp256k1_frost_nonce_destroy(data->state[i].sign_nonce);
            data->state[i].sign_nonce = NULL;
        }

        for (j = 0; j < BENCH_FROST_THR_PARTICIPANTS; j++) {
            fill_random(binding_seed, sizeof(binding_seed));
            fill_random(hiding_seed, sizeof(hiding_seed));

            nonce = secp256k1_frost_nonce_create(
                data->ctx,
                &data->state[i].keypairs[j],
                binding_seed,
                hiding_seed
            );
            CHECK(nonce != NULL);

            memcpy(
                &data->state[i].signing_commitments[j],
                &nonce->commitments,
                sizeof(secp256k1_frost_nonce_commitment)
            );

            if (j == signer_index) {
                data->state[i].sign_nonce = nonce;
            } else {
                /*
                 * Only the measured signer's secret nonce is needed by
                 * bench_frost_sign(). The other signers' public commitments
                 * have already been copied into signing_commitments.
                 */
                secp256k1_frost_nonce_destroy(nonce);
            }
        }

        CHECK(data->state[i].sign_nonce != NULL);
    }
}

static void bench_frost_sign(void *arg, int iters) {
    bench_frost_data *data = (bench_frost_data *)arg;
    secp256k1_frost_signature_share signature_share;
    int i, signer_index;

    for (i = 0; i < iters; i++) {
        signer_index = i % BENCH_FROST_THR_PARTICIPANTS;

        CHECK(data->state[i].sign_nonce != NULL);

        CHECK(secp256k1_frost_sign(data->ctx,
                                   &signature_share,
                                   data->msgs[i],
                                   BENCH_FROST_MSGLEN,
                                   BENCH_FROST_THR_PARTICIPANTS,
                                   &data->state[i].keypairs[signer_index],
                                   data->state[i].sign_nonce,
                                   data->state[i].signing_commitments) == 1);
    }
}

static void bench_frost_sign_teardown(void *arg, int iters) {
    bench_frost_data *data = (bench_frost_data *)arg;
    int i;

    /*
     * secp256k1_frost_sign() has cleared the secret nonce fields. Destroy the
     * objects here to release their allocations before the next benchmark run.
     */
    for (i = 0; i < iters; i++) {
        if (data->state[i].sign_nonce != NULL) {
            secp256k1_frost_nonce_destroy(data->state[i].sign_nonce);
            data->state[i].sign_nonce = NULL;
        }
    }
}

static void bench_frost_aggregate(void* arg, int iters) {
    bench_frost_data *data = (bench_frost_data *)arg;
    int i, signer_index;
    unsigned char signature[FROST_SIGNATURE_SIZE];

    for (i = 0; i < iters; i++) {
        signer_index = i % BENCH_FROST_THR_PARTICIPANTS;

        CHECK(secp256k1_frost_aggregate(data->ctx,
                                        signature,
                                        data->msgs[i],
                                        BENCH_FROST_MSGLEN,
                                        &data->state[i].keypairs[signer_index],
                                        data->state[i].public_keys,
                                        data->state[i].aggregate_commitments,
                                        data->state[i].signature_shares,
                                        BENCH_FROST_THR_PARTICIPANTS) == 1);
    }
}

static void bench_frost_verify(void* arg, int iters) {
    bench_frost_data *data = (bench_frost_data *)arg;
    int i;

    for (i = 0; i < iters; i++) {
        CHECK(secp256k1_frost_verify(data->ctx,
                                     data->state[i].signature,
                                     data->msgs[i],
                                     BENCH_FROST_MSGLEN,
                                     data->state[i].public_keys) == 1);
    }
}

static void bench_frost_data_init(bench_frost_data *data, int iters) {
    int i, j;
    unsigned char hiding_seed[32], binding_seed[32];
    secp256k1_frost_vss_commitments *dealer_commitments;
    secp256k1_frost_keygen_secret_share shares_by_participant[BENCH_FROST_MAX_PARTICIPANTS];
    secp256k1_frost_nonce *aggregate_nonces[BENCH_FROST_THR_PARTICIPANTS];
    unsigned char *msg;

    /* Allocate benchmark data */
    data->ctx = secp256k1_context_create(SECP256K1_CONTEXT_NONE);
    data->n = iters;
    data->state = (secp256k1_frost_data_per_iter *)malloc(iters * sizeof(secp256k1_frost_data_per_iter));
    data->msgs = (const unsigned char **)malloc(iters * sizeof(unsigned char *));

    CHECK(data->ctx != NULL);
    CHECK(data->state != NULL);
    CHECK(data->msgs != NULL);

    /*
     * Prepare immutable aggregation/verification data for each iteration.
     * Signing-benchmark nonces are deliberately not created here; they are
     * created by bench_frost_sign_setup() before every timed run.
     */
    for (i = 0; i < iters; i++) {
        memset(&data->state[i], 0, sizeof(data->state[i]));

        msg = (unsigned char *)malloc(BENCH_FROST_MSGLEN);
        data->state[i].keypairs = (secp256k1_frost_keypair *) malloc(BENCH_FROST_MAX_PARTICIPANTS * sizeof(secp256k1_frost_keypair));
        data->state[i].signing_commitments = (secp256k1_frost_nonce_commitment *)malloc(BENCH_FROST_THR_PARTICIPANTS * sizeof(secp256k1_frost_nonce_commitment));
        data->state[i].aggregate_commitments = (secp256k1_frost_nonce_commitment *)malloc(BENCH_FROST_THR_PARTICIPANTS * sizeof(secp256k1_frost_nonce_commitment));
        data->state[i].public_keys = (secp256k1_frost_pubkey *)malloc(BENCH_FROST_THR_PARTICIPANTS * sizeof(secp256k1_frost_pubkey));
        data->state[i].signature_shares = (secp256k1_frost_signature_share *)malloc(BENCH_FROST_THR_PARTICIPANTS * sizeof(secp256k1_frost_signature_share));

        CHECK(msg != NULL);
        CHECK(data->state[i].keypairs != NULL);
        CHECK(data->state[i].signing_commitments != NULL);
        CHECK(data->state[i].aggregate_commitments != NULL);
        CHECK(data->state[i].public_keys != NULL);
        CHECK(data->state[i].signature_shares != NULL);

        data->state[i].sign_nonce = NULL;

        /* Message Generation */
        msg[0] = i; msg[1] = i >> 8; msg[2] = i >> 16; msg[3] = i >> 24;
        memset(&msg[4], 'm', BENCH_FROST_MSGLEN - 4);
        data->msgs[i] = msg;

        /* Key Generation */
        dealer_commitments = secp256k1_frost_vss_commitments_create(BENCH_FROST_THR_PARTICIPANTS);
        CHECK(dealer_commitments != NULL);

        CHECK(secp256k1_frost_keygen_with_dealer(data->ctx,
                                                 dealer_commitments,
                                                 shares_by_participant,
                                                 data->state[i].keypairs,
                                                 BENCH_FROST_MAX_PARTICIPANTS,
                                                 BENCH_FROST_THR_PARTICIPANTS) == 1);

        secp256k1_frost_vss_commitments_destroy(dealer_commitments);

        /* Extract the public keys of the participating signers. */
        for (j = 0; j < BENCH_FROST_THR_PARTICIPANTS; j++) {
            CHECK(secp256k1_frost_pubkey_from_keypair(&data->state[i].public_keys[j], &data->state[i].keypairs[j]) == 1);
        }

        /*
         * Build a separate valid signing session used only to prepare the
         * immutable aggregation and verification benchmark inputs.
         */
        for (j = 0; j < BENCH_FROST_THR_PARTICIPANTS; j++) {
            fill_random(binding_seed, sizeof(binding_seed));
            fill_random(hiding_seed, sizeof(hiding_seed));
            aggregate_nonces[j] = secp256k1_frost_nonce_create(data->ctx,
                                                                    &data->state[i].keypairs[j],
                                                                    binding_seed,
                                                                    hiding_seed);
            CHECK(aggregate_nonces[j] != NULL);

            memcpy(&data->state[i].aggregate_commitments[j], 
                   &(aggregate_nonces[j]->commitments), sizeof(secp256k1_frost_nonce_commitment));
        }

        for (j = 0; j < BENCH_FROST_THR_PARTICIPANTS; j++) {
            CHECK(secp256k1_frost_sign(data->ctx,
                                       &data->state[i].signature_shares[j],
                                       data->msgs[i],
                                       BENCH_FROST_MSGLEN,
                                       BENCH_FROST_THR_PARTICIPANTS,
                                       &data->state[i].keypairs[j],
                                       aggregate_nonces[j],
                                       data->state[i].aggregate_commitments) == 1);

            /*
             * sign() has consumed the secret nonce fields. The public
             * commitments have already been retained in aggregate_commitments.
             */
            secp256k1_frost_nonce_destroy(aggregate_nonces[j]);
            aggregate_nonces[j] = NULL;
        }

        CHECK(secp256k1_frost_aggregate(data->ctx,
                                        data->state[i].signature,
                                        data->msgs[i],
                                        BENCH_FROST_MSGLEN,
                                        &data->state[i].keypairs[0],
                                        data->state[i].public_keys,
                                        data->state[i].aggregate_commitments,
                                        data->state[i].signature_shares,
                                        BENCH_FROST_THR_PARTICIPANTS) == 1);
    }
}

static void bench_frost_data_cleanup(bench_frost_data *data, int iters) {
    int i;

    for (i = 0; i < iters; i++) {
        if (data->state[i].sign_nonce != NULL) {
            secp256k1_frost_nonce_destroy(data->state[i].sign_nonce);
            data->state[i].sign_nonce = NULL;
        }

        free((void *)data->msgs[i]);
        free(data->state[i].keypairs);
        free(data->state[i].signing_commitments);
        free(data->state[i].aggregate_commitments);
        free(data->state[i].public_keys);
        free(data->state[i].signature_shares);
    }
    free((void *) (*data).msgs);
    free((void *) (*data).state);
    secp256k1_context_destroy((*data).ctx);
}

static void run_frost_bench(int iters, int argc, char** argv) {
    bench_frost_data data;
    int d = argc == 1;
    int runs = 10;
    char frost_aggregate_label[32];

    bench_frost_data_init(&data, iters);

    if (d || have_flag(argc, argv, "frost") || have_flag(argc, argv, "sign")
        || have_flag(argc, argv, "frost_sign")){
        run_benchmark("frost_sign", bench_frost_sign, bench_frost_sign_setup, bench_frost_sign_teardown,
                      (void *) &data, runs, iters);
    }
    if (d || have_flag(argc, argv, "frost") || have_flag(argc, argv, "aggregate")
        || have_flag(argc, argv, "frost_aggregate")){
        sprintf(frost_aggregate_label, "frost_aggregate (%d/%d)",
                BENCH_FROST_THR_PARTICIPANTS, BENCH_FROST_MAX_PARTICIPANTS);
        run_benchmark(frost_aggregate_label,
                      bench_frost_aggregate, NULL, NULL,
                      (void *) &data, runs, iters);
    }
    if (d || have_flag(argc, argv, "frost") || have_flag(argc, argv, "verify")
        || have_flag(argc, argv, "frost_verify")){
        run_benchmark("frost_verify", bench_frost_verify, NULL, NULL,
                      (void *) &data, runs, iters);
    }

    /* Cleaning up data */
    bench_frost_data_cleanup(&data, iters);
}

#endif /* SECP256K1_MODULE_FROST_BENCH_H */
